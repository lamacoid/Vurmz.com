// Compiles the designer's SVG templates and the outlining font map into
// TypeScript so the edge bundle needs no filesystem. Run after editing
// anything in lib/designer/templates/ or app/fonts.css:
//   node scripts/build-designer-templates.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import { fileURLToPath } from 'node:url'
const ROOT = fileURLToPath(new URL('..', import.meta.url))
const CARDS = join(ROOT, 'lib/designer/templates/cards')
const OUT = join(ROOT, 'lib/designer/templates.generated.ts')
const FONTS_OUT = join(ROOT, 'lib/designer/font-files.generated.ts')

// ---- templates -----------------------------------------------------------
const manifest = JSON.parse(readFileSync(join(CARDS, 'manifest.json'), 'utf8'))
const attr = (tag, name) => {
  const m = tag.match(new RegExp(`\\s${name}="([^"]*)"`))
  return m ? m[1] : undefined
}
const num = v => (v === undefined ? undefined : Number(v))

const templates = manifest.map(entry => {
  const svg = readFileSync(join(CARDS, `${entry.key}.svg`), 'utf8')
  const slots = []
  for (const m of svg.matchAll(/<(text|rect)\b([^>]*)data-slot="([^"]+)"([^>]*)>(?:([^<]*)<\/text>)?/g)) {
    const [, tag, a, name, b, inner] = m
    const attrs = a + b
    if (tag === 'text') {
      slots.push({
        name, kind: 'text', sample: (inner ?? '').trim(),
        x: num(attr(attrs, 'x')), y: num(attr(attrs, 'y')),
        sizeMm: num(attr(attrs, 'font-size')),
        fontFamily: attr(attrs, 'font-family'),
        anchor: attr(attrs, 'text-anchor') ?? 'start',
        letterSpacing: num(attr(attrs, 'letter-spacing')) ?? 0,
        smallCaps: attr(attrs, 'font-variant') === 'small-caps',
      })
    } else {
      slots.push({
        name, kind: 'rect',
        x: num(attr(attrs, 'x')), y: num(attr(attrs, 'y')),
        w: num(attr(attrs, 'width')), h: num(attr(attrs, 'height')),
      })
    }
  }
  // The body of the SVG without the outer element, safe rect, title, desc.
  const body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<title>[\s\S]*?<\/title>/, '')
    .replace(/<desc>[\s\S]*?<\/desc>/, '')
    .replace(/<rect id="safe"[^>]*\/>/, '')
    .trim()
  return { key: entry.key, label: entry.label, kind: entry.kind, description: entry.description ?? '', slots, body }
})

const header = `// GENERATED by scripts/build-designer-templates.mjs. Do not edit.\n// Source: lib/designer/templates/cards/*.svg (from the 2026-09-12 handoff).\n`
writeFileSync(OUT, header + `
export interface DesignerSlot {
  name: string
  kind: 'text' | 'rect'
  x: number
  y: number
  /** text */
  sample?: string
  sizeMm?: number
  fontFamily?: string
  anchor?: 'start' | 'middle' | 'end'
  letterSpacing?: number
  smallCaps?: boolean
  /** rect */
  w?: number
  h?: number
}
export interface DesignerTemplate {
  key: string
  label: string
  kind: 'business' | 'other'
  description: string
  slots: DesignerSlot[]
  /** Inner SVG markup in card millimetres (viewBox 0 0 85.725 53.975). */
  body: string
}
export const CARD_TEMPLATES: DesignerTemplate[] = ${JSON.stringify(templates, null, 2)}
`)

// ---- fonts ---------------------------------------------------------------
// family name -> a TTF/OTF url the outliner can parse. woff2 faces are
// skipped (opentype.js cannot read them); Zen Kurenaido gets its TTF.
const css = readFileSync(join(ROOT, 'app/fonts.css'), 'utf8')
const files = {}
for (const m of css.matchAll(/@font-face\s*{([^}]*)}/g)) {
  const block = m[1]
  const fam = block.match(/font-family:\s*'([^']+)'/)?.[1]
  const url = [...block.matchAll(/url\(['"]?([^'")]+)['"]?\)/g)].map(x => x[1]).find(u => /\.(ttf|otf)$/i.test(u))
  if (fam && url && !files[fam]) files[fam] = url
}
files['Zen Kurenaido'] = '/fonts/ZenKurenaido-Regular.ttf'
files['Inter'] = '/fonts/designer/Inter-Regular.ttf'
files['Fraunces'] = '/fonts/designer/Fraunces-Regular.ttf'
files['Allura'] = '/fonts/designer/Allura-Regular.ttf'
writeFileSync(FONTS_OUT, header + `
/** CSS font-family name -> TTF/OTF path under public/, for outlining. */
export const FONT_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)}
`)
console.log(`${templates.length} templates, ${Object.keys(files).length} outline fonts`)
